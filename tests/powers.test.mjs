import assert from 'node:assert/strict';
import {chargeRatio,chargedJumpSpeed,findClimbWall,roofAt,landingHeight,thunderclapContains,SUPER_JUMP_CHARGE_SECONDS} from '../src/powers.mjs';
assert.equal(chargeRatio(-5),0);
assert.equal(chargeRatio(SUPER_JUMP_CHARGE_SECONDS),1);
assert.equal(chargeRatio(50),1);
assert.equal(chargedJumpSpeed(0),23);
assert(chargedJumpSpeed(SUPER_JUMP_CHARGE_SECONDS)>57);
assert(chargedJumpSpeed(1,true)>chargedJumpSpeed(1,false));
const block={x:12,z:4,w:12,d:10,h:30,alive:true};
let wall=findClimbWall(4.5,4,0,[block]);
assert(wall && wall.normalX===-1 && Math.abs(wall.x-(12-6-1.26-.12))<1e-6);
assert.equal(findClimbWall(1,4,0,[block]),null);
assert.equal(findClimbWall(4.5,4,31,[block]),null);
assert.equal(findClimbWall(4.5,4,0,[{...block,alive:false}]),null);
assert.equal(findClimbWall(4.5,25,0,[block]),null);
assert.equal(roofAt(12,4,[block]),30);
assert.equal(roofAt(0,4,[block]),0);
assert.equal(landingHeight(12,4,40,25,[block]),30);
assert.equal(landingHeight(12,4,20,10,[block]),null);
assert.equal(landingHeight(12,4,10,20,[block]),null);
assert.equal(landingHeight(0,0,2,-1,[block]),0);
assert.equal(thunderclapContains(9,4,1,0,18),true);
assert.equal(thunderclapContains(-6,0,1,0,18),false);
assert.equal(thunderclapContains(5,15,1,0,18),false);
console.log('20 Hulk power physics cases: OK');
