import assert from 'node:assert/strict';
import {circleRectOverlap,segmentAABB2D,segmentSphere3D,moveCircleSlide,sweptBuildingHit} from '../src/physics.mjs';
const building={x:5,z:0,w:2,d:6,h:14,alive:true};
assert.equal(circleRectOverlap(2.99,0,1,building),false,'outside wall');
assert.equal(circleRectOverlap(3.01,0,1,building),true,'touching wall');
let hit=segmentAABB2D(0,0,10,0,building,1);
assert(Math.abs(hit.t-.3)<1e-5,'sweep detects first impact, not final point');
assert.equal(hit.nx,-1);
let moved=moveCircleSlide(0,0,10,0,1,[building]);
assert(moved.x<3,'no wall tunneling');
assert(moved.x>2.85,'moves up to solid wall');
moved=moveCircleSlide(0,1,10,6,1,[building]);
assert(moved.x<=3.05,'slide against wall');
assert(moved.z>2,'preserves tangential motion');
moved=moveCircleSlide(0,0,100,0,1,[building]);
assert(moved.x<3,'high speed cannot tunnel');
moved=moveCircleSlide(157,0,40,0,1,[]);
assert(moved.x<=158,'world boundary');
assert.equal(segmentSphere3D(-10,3,0,10,3,0,0,3,0,2),.4,'swept projectile hits sphere');
assert.equal(segmentSphere3D(-10,3,0,10,3,0,0,10,0,2),null,'misses sphere vertically');
const wall=sweptBuildingHit({x:0,y:10,z:0},{x:12,y:10,z:0},[building],.3);
assert(wall && wall.t>.2 && wall.t<.4,'projectile hits building at height');
assert.equal(sweptBuildingHit({x:0,y:22,z:0},{x:12,y:22,z:0},[building],.3),null,'projectile above roof misses');
assert.equal(sweptBuildingHit({x:0,y:10,z:0},{x:12,y:10,z:0},[{...building,alive:false}],.3),null,'ruins do not block');
console.log('12 collision test cases: OK');
